"""Deterministic answer rendering for the rule engine.

These templates are the same shapes the SFT data teaches (§49), which is
deliberate: it makes the rule engine a meaningful floor in the benchmark. If a
fine-tuned model cannot beat templated text on financial correctness, the
fine-tune is not ready, and the comparison in ai/evaluation/compare_models.py
will say so.

Nothing here computes. Every figure is read out of a tool payload produced by
``app.calculations`` / ``app.scoring``.
"""

from __future__ import annotations

from typing import Any

from ai.datasets.builders.common import money, pct, years


def render_answer(payload: dict[str, Any], *, question: str = "") -> str:
    tool = payload.get("tool")
    data = payload.get("data") or {}
    warnings = payload.get("warnings") or []
    renderer = _RENDERERS.get(tool)
    if renderer is None:
        return _generic_from_payload(payload)
    text = renderer(data, warnings)
    return text


def _warn_block(warnings: list[str]) -> str:
    return (" " + " ".join(warnings)) if warnings else ""


def _search(data: dict, warnings: list[str]) -> str:
    bonds = data.get("bonds") or []
    if not bonds:
        return (
            "## Коротко\nПод эти условия на KASE ничего не нашлось.\n\n"
            "## Что проверить\nПопробуйте смягчить одно из условий — срок, валюту или "
            "минимальную доходность."
        )
    lines = [
        f"- {b['ticker']} — доходность {pct(b['ytm_pct'])}, после инфляции {pct(b['real_ytm_pct'])}, "
        f"надёжность {b['credit_score']}, ликвидность {b['liquidity_score']}, "
        f"погашение {b['maturity_date']}"
        for b in bonds
    ]
    filters = data.get("filters") or {}
    constraint = ", ".join(f"{k}={v}" for k, v in filters.items() if k != "limit")
    return (
        f"## Коротко\nПод ваши условия подходит {data.get('count')} "
        f"{'выпуск' if data.get('count') == 1 else 'выпусков'}, показываю "
        f"{len(bonds)} — данные KASE и расчет системы.\n\n"
        f"## Почему\n" + "\n".join(lines) + f"\n\nОтбор шёл по: {constraint or 'без фильтров'}.\n\n"
        "## Основные риски\nБолее высокая доходность в этом списке почти всегда означает более "
        "низкую оценку надёжности или худшую ликвидность — AI-интерпретация. Список не является "
        "рекомендацией к покупке.\n\n"
        "## Что проверить\nПо каждому выпуску — наличие заявок на продажу нужного объёма и дату "
        "ближайшего купона."
    )


def _bond(data: dict, warnings: list[str]) -> str:
    scores = data.get("scores") or {}
    issuer = data.get("issuer") or {}
    return (
        f"## Коротко\n{data['ticker']} — выпуск {issuer.get('name')}, погашение "
        f"{data['maturity_date']} (через {years(data.get('years_to_maturity'))}). Доходность "
        f"{pct(data.get('ytm_pct'))} годовых — данные KASE, после инфляции "
        f"{pct(data.get('real_ytm_pct'))} — расчет системы.\n\n"
        f"## Почему\nКупон {pct(data.get('coupon_rate_pct'))} годовых, номинал "
        f"{money(data.get('nominal'), data.get('currency', 'KZT'))}, выплаты "
        f"{data.get('coupon_frequency') or '—'} раз в год. Надёжность эмитента "
        f"{scores.get('credit')} из 100, ликвидность {scores.get('liquidity')} из 100, общая "
        f"оценка {scores.get('investment') or scores.get('hold')} из 100 — расчет системы.\n\n"
        f"## Основные риски\nВы зависите от платёжеспособности эмитента"
        f"{' (банк — оценка по банковской модели)' if issuer.get('is_bank') else ''}. При продаже "
        f"до погашения цена может отличаться от сегодняшней.{_warn_block(warnings)}\n\n"
        f"## Что проверить\nДату ближайшего купона ({data.get('next_coupon_date') or 'не опубликована'}) "
        f"и свежесть отчётности эмитента."
    )


def _quote(data: dict, warnings: list[str]) -> str:
    return (
        f"## Коротко\nПо {data['ticker']} последняя цена {data.get('last')}% от номинала, "
        f"спрос {data.get('bid')}, предложение {data.get('ask')} — данные KASE на "
        f"{data.get('as_of')}.\n\n"
        f"## Почему\nДоходность к погашению по этой цене {pct(data.get('ytm_pct'))}, накопленный "
        f"купонный доход {data.get('accrued_interest')}% номинала. Оборот "
        f"{money(data.get('turnover'))}, сделок за сессию {data.get('number_of_trades')}.\n\n"
        f"## Основные риски\nЭто итоги торговой сессии, а не стакан в реальном времени."
        f"{_warn_block(warnings)}\n\n"
        f"## Что проверить\nЕсть ли сейчас заявка на продажу нужного вам объёма."
    )


def _investment(data: dict, warnings: list[str]) -> str:
    currency = data.get("currency", "KZT")
    if not data.get("quantity"):
        return (
            "## Коротко\nНа эту сумму не получится купить даже одну облигацию.\n\n"
            f"## Почему\nМинимально необходимая сумма — "
            f"{money(data.get('minimum_required_amount'), currency)}.{_warn_block(warnings)}\n\n"
            "## Что проверить\nУвеличьте сумму или посмотрите выпуски с меньшим номиналом."
        )
    return (
        f"## Коротко\nПолучится купить {data['quantity']} "
        f"{'облигацию' if data['quantity'] == 1 else 'облигаций'}. При удержании до погашения вы "
        f"получите {money(data.get('total_cash_received'), currency)}, прибыль — "
        f"{money(data.get('total_profit'), currency)} — расчет системы.\n\n"
        f"## Почему\nПокупка обойдётся в {money(data.get('total_purchase_cost'), currency)}, "
        f"останется {money(data.get('cash_remaining'), currency)}. Купонами придёт "
        f"{money(data.get('coupon_income'), currency)}, номиналом вернётся "
        f"{money(data.get('principal_repayment'), currency)} — это ваши же деньги, не прибыль. "
        f"Доходность {pct(data.get('annualized_return_percent'))} годовых, после инфляции "
        f"{pct(data.get('real_annualized_return_percent'))} — расчет системы.\n\n"
        f"## Основные риски\nРасчёт исходит из того, что эмитент заплатит всё по графику и что вы "
        f"додержите до погашения. Это не гарантия.{_warn_block(warnings)}\n\n"
        f"## Что будет с {money(data.get('input_amount'), currency)}\n"
        f"Вложено {money(data.get('total_purchase_cost'), currency)} → получено "
        f"{money(data.get('total_cash_received'), currency)} за "
        f"{years(data.get('holding_period_years'))}. Реальная прибыль после инфляции — "
        f"{money(data.get('real_profit'), currency)} — расчет системы.\n\n"
        f"## Что проверить\nКомиссию брокера — в расчёте её нет."
    )


def _ytm(data: dict, warnings: list[str]) -> str:
    return (
        f"## Коротко\nДоходность к погашению {data['ticker']} — {pct(data.get('ytm_pct'))} годовых "
        f"при цене {data.get('clean_price')}% от номинала — расчет системы. После инфляции "
        f"{pct(data.get('real_ytm_pct'))}.\n\n"
        f"## Почему\nДоходность к погашению учитывает и купоны, и цену покупки, и возврат "
        f"номинала — поэтому она отличается от купонной ставки. Дюрация "
        f"{data.get('duration_years')} года, модифицированная дюрация "
        f"{data.get('modified_duration')}, выпуклость {data.get('convexity')}.\n\n"
        f"## Основные риски\nЭта доходность реализуется только при удержании до погашения и "
        f"своевременных выплатах эмитента. При росте ставок на 1 процентный пункт цена упадёт "
        f"примерно на {pct(data.get('modified_duration'))}.{_warn_block(warnings)}\n\n"
        f"## Что проверить\nЧто цена, по которой считали, реально доступна для покупки."
    )


def _cashflows(data: dict, warnings: list[str]) -> str:
    payments = data.get("payments") or []
    first, last = payments[0], payments[-1]
    currency = data.get("currency", "KZT")
    return (
        f"## Коротко\nБлижайшая выплата по {data['ticker']} — {first['date']}, "
        f"{money(first['total'], currency)} на {data.get('quantity')} "
        f"{'бумагу' if data.get('quantity') == 1 else 'бумаг'} — данные KASE. Всего впереди "
        f"{len(payments)} выплат.\n\n"
        f"## Почему\nКупон — это процент от номинала по графику эмитента, а не доход от роста "
        f"цены. Последняя выплата {last['date']} больше остальных: вместе с купоном возвращается "
        f"номинал {money(last['principal'], currency)}.\n\n"
        f"## Основные риски\nГрафик — обязательство эмитента, а не гарантия.{_warn_block(warnings)}\n\n"
        f"## Что проверить\nПри покупке вы доплачиваете продавцу накопленный купонный доход за дни "
        f"с прошлой выплаты."
    )


def _financials(data: dict, warnings: list[str]) -> str:
    periods = data.get("periods") or []
    latest = periods[0]
    currency = data.get("currency", "KZT")
    model = "банковской" if data.get("is_bank") else "корпоративной"
    return (
        f"## Коротко\nПоследний отчётный период {data['issuer_name']} — {latest['period_end']}: "
        f"активы {money(latest.get('total_assets'), currency)}, капитал "
        f"{money(latest.get('total_equity'), currency)}, прибыль "
        f"{money(latest.get('net_profit'), currency)} — данные отчётности эмитента на KASE.\n\n"
        f"## Почему\nЭмитент оценивается по {model} модели. Выручка "
        f"{money(latest.get('revenue'), currency)}, обязательства "
        f"{money(latest.get('total_liabilities'), currency)}. Показатели, которых нет в "
        f"публикации, не заполняются и не приравниваются к нулю.\n\n"
        f"## Основные риски\nОтчётность описывает прошлое, а платить эмитенту предстоит в "
        f"будущем — AI-интерпретация.{_warn_block(warnings)}\n\n"
        f"## Что проверить\nГрафик погашения долга эмитента и статус аудита отчётности."
    )


def _compare(data: dict, warnings: list[str]) -> str:
    rows = data.get("bonds") or []
    lines = [
        f"- {r['ticker']}: доходность {pct(r['ytm_pct'])}, после инфляции {pct(r['real_ytm_pct'])}, "
        f"надёжность {r['credit_score']}, ликвидность {r['liquidity_score']}, срок "
        f"{years(r['years_to_maturity'])}"
        for r in rows
    ]
    scored = [r for r in rows if r.get("real_ytm_pct") is not None]
    top = max(scored, key=lambda r: r["real_ytm_pct"]) if scored else None
    safest = max(
        [r for r in rows if r.get("credit_score") is not None],
        key=lambda r: r["credit_score"],
        default=None,
    )
    return (
        f"## Коротко\nБольше всего после инфляции даёт {top['ticker'] if top else '—'}, выше "
        f"оценка надёжности у {safest['ticker'] if safest else '—'} — расчет системы. Что из "
        f"этого «лучше», зависит от вашего срока и терпимости к риску.\n\n"
        f"## Почему\n" + "\n".join(lines) + "\n\n"
        "## Основные риски\nРазница в доходности между этими выпусками — это плата за разный "
        "риск, а не бесплатный выигрыш — AI-интерпретация.\n\n"
        "## Что проверить\nСовпадает ли срок выпуска с вашим горизонтом. Решение о покупке я не "
        "принимаю."
    )


def _inflation(data: dict, warnings: list[str]) -> str:
    return (
        f"## Коротко\nОфициальная годовая инфляция в Казахстане — "
        f"{pct(data.get('annual_rate_pct'))} на {data.get('period_end')} — данные stat.gov.kz.\n\n"
        f"## Почему\nИменно эта величина используется в расчёте реальной доходности по формуле "
        f"Фишера: (1 + доходность) / (1 + инфляция) − 1. Разность «доходность минус инфляция» "
        f"завышает результат и не применяется.\n\n"
        f"## Что проверить\nДату публикации: инфляция обновляется ежемесячно."
    )


def _real_return(data: dict, warnings: list[str]) -> str:
    total = (
        f" За {data['years']} года номинально сумма вырастет на {pct(data.get('total_nominal_pct'))}, "
        f"по покупательной способности — на {pct(data.get('total_real_pct'))}."
        if data.get("years") else ""
    )
    return (
        f"## Коротко\nПри номинальной доходности {pct(data.get('nominal_return_pct'))} и инфляции "
        f"{pct(data.get('inflation_pct'))} реальная доходность — "
        f"{pct(data.get('real_return_pct'))} годовых — расчет системы.\n\n"
        f"## Почему\n{data.get('method')}. {data.get('note')}{total}\n\n"
        f"## Основные риски\nЕсли инфляция за срок владения окажется выше сегодняшней, реальный "
        f"результат будет меньше — вплоть до отрицательного.\n\n"
        f"## Что проверить\nНа какую дату взята инфляция в расчёте."
    )


def _source(data: dict, warnings: list[str]) -> str:
    lines = [
        f"- {s.get('field')}: {s.get('source')}, {s.get('source_url')}, получено {s.get('fetched_at')}"
        for s in data.get("sources", [])
    ]
    return (
        "## Коротко\nВот источники значений, о которых вы спросили — данные KASE.\n\n"
        "## Почему\n" + "\n".join(lines) + "\n\nКаждое значение в системе хранится вместе с "
        "источником, ссылкой и временем получения.\n\n"
        "## Что проверить\nВозраст данных: если с момента получения прошло много времени, "
        "расчёты по ним стоит обновить."
    )


_RENDERERS = {
    "search_bonds": _search,
    "get_bond": _bond,
    "get_quote": _quote,
    "calculate_investment": _investment,
    "calculate_ytm": _ytm,
    "get_cashflows": _cashflows,
    "get_financials": _financials,
    "compare_bonds": _compare,
    "get_inflation": _inflation,
    "calculate_real_return": _real_return,
    "get_source": _source,
}


def _generic_from_payload(payload: dict[str, Any]) -> str:
    return (
        "## Коротко\nДанные получены, но у меня нет шаблона для их изложения.\n\n"
        f"## Почему\nИнструмент {payload.get('tool')} вернул результат типа "
        f"{payload.get('kind')}.\n\n"
        "## Что проверить\nПереформулируйте вопрос — я подберу подходящий инструмент."
    )


